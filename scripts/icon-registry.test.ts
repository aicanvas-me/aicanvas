import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { generateIconRegistry } from './icon-registry.mjs'

const OUTPUT_ROOT = fileURLToPath(new URL('../registry-data/', import.meta.url))
const MARKER = ['AICANVAS', 'PREMIUM', 'DO', 'NOT', 'COMMIT'].join('-')
const NAMES = ['search', 'image-sparkle', 'map']
const STYLES = [
  { suffix: '', componentSuffix: '', style: 'line', path: 'M1 1L2 2' },
  { suffix: '-duotone', componentSuffix: 'Duotone', style: 'duotone', path: 'M3 3L4 4' },
  { suffix: '-solid', componentSuffix: 'Solid', style: 'solid', path: 'M10 10H20V20Z' },
  { suffix: '-solid-duotone', componentSuffix: 'SolidDuotone', style: 'solid-duotone', path: 'M15 15H21V21Z' },
]

interface RegistryFile {
  path: string
  content: string
  type: string
  target: string
}

interface RegistryItem {
  name: string
  files: RegistryFile[]
  registryDependencies?: string[]
}

let workDir: string
let sourceDir: string
let outDir: string

function readItem(name: string): RegistryItem {
  return JSON.parse(readFileSync(join(outDir, `${name}.json`), 'utf8'))
}

beforeEach(() => {
  mkdirSync(OUTPUT_ROOT, { recursive: true })
  workDir = mkdtempSync(join(OUTPUT_ROOT, '.icon-registry-test-'))
  sourceDir = join(workDir, 'source')
  outDir = join(workDir, 'output')
  mkdirSync(join(sourceDir, 'react/icons'), { recursive: true })
  writeFileSync(join(sourceDir, 'react/IconBase.tsx'), `// ${MARKER}\nexport const createIcon = () => null\n`)
  // A package barrel must never be shipped as an icon.
  writeFileSync(join(sourceDir, 'react/icons/index.ts'), 'export {}\n')
  for (const name of NAMES) {
    const component = name.split('-').map((word) => word[0].toUpperCase() + word.slice(1)).join('')
    for (const { suffix, componentSuffix, style, path } of STYLES) {
      const exported = component + componentSuffix
      writeFileSync(join(sourceDir, `react/icons/${name}${suffix}.tsx`), [
        `// ${MARKER} - source marker`,
        '// Generated by icons/tools/react.mjs from icons/src. Do not edit by hand.',
        "import { createIcon } from '../IconBase'",
        '',
        `export const ${exported} = /* @__PURE__ */ createIcon("${name}", "${style}", [["path", {"d":"${path}"}]])`,
        '// Alias for names that clash (Image, Link, Map).',
        `export const ${exported}Icon = ${exported}`,
        '',
      ].join('\n'))
    }
  }
  vi.spyOn(console, 'log').mockImplementation(() => {})
})

afterEach(() => {
  vi.restoreAllMocks()
  rmSync(workDir, { recursive: true, force: true })
})

describe('icon registry generator', () => {
  it('writes individual style items, a base, and a self-contained Line set without changing other outputs', () => {
    mkdirSync(outDir)
    const untouched = ['registry.json', '_manifest.json', 'existing-component.json']
    for (const filename of untouched) writeFileSync(join(outDir, filename), '{"keep":true}\n')

    expect(generateIconRegistry({ sourceDir, outDir, baseUrl: 'https://registry.example///' }))
      .toEqual({ iconCount: 3, itemCount: 14 })
    expect(readdirSync(outDir)).toHaveLength(18)
    for (const filename of untouched) expect(readFileSync(join(outDir, filename), 'utf8')).toBe('{"keep":true}\n')

    const base = readItem('icon-base')
    expect(base.name).toBe('icon-base')
    expect(base.files).toEqual([{
      path: 'components/icons/IconBase.tsx',
      content: 'export const createIcon = () => null\n',
      type: 'registry:ui',
      target: 'components/icons/IconBase.tsx',
    }])
    expect(base.registryDependencies).toBeUndefined()

    for (const name of NAMES) {
      for (const { suffix } of STYLES) {
        const item = readItem(`icon-${name}${suffix}`)
        expect(item).toMatchObject({
          $schema: 'https://ui.shadcn.com/schema/registry-item.json',
          name: `icon-${name}${suffix}`,
          type: 'registry:ui',
          title: expect.any(String),
          description: expect.any(String),
          author: 'aicanvas <https://aicanvas.me>',
          registryDependencies: ['https://registry.example/r/icon-base.json'],
        })
        expect(item).not.toHaveProperty('dependencies')
        expect(item).not.toHaveProperty('devDependencies')
        expect(item.files).toHaveLength(1)
        expect(item.files[0]).toMatchObject({
          path: `components/icons/${name}${suffix}.tsx`,
          target: `components/icons/${name}${suffix}.tsx`,
          type: 'registry:ui',
        })
      }
    }
    expect(readItem('icon-search-duotone')).toHaveProperty('title', 'Search icon (Duotone)')

    const bundle = readItem('icons')
    expect(bundle.name).toBe('icons')
    expect(bundle.registryDependencies).toBeUndefined()
    expect(bundle).not.toHaveProperty('dependencies')
    expect(bundle.files).toEqual([base.files[0], ...[...NAMES].sort().map((name) => readItem(`icon-${name}`).files[0])])
  })

  it('strips only the specified lines and rewrites the runtime import in every shipped file', () => {
    generateIconRegistry({ sourceDir, outDir })
    for (const filename of readdirSync(outDir).filter((file) => file !== 'icons-index.json')) {
      const item = readItem(filename.slice(0, -5))
      for (const file of item.files) {
        expect(file.content).not.toContain(MARKER)
        expect(file.content).not.toContain('// Generated by icons/tools/react.mjs')
        expect(file.content).not.toContain('// Alias for names that clash')
        if (file.target.endsWith('/IconBase.tsx')) continue
        expect(file.content).toContain("from './IconBase'")
        expect(file.content).not.toContain("from '../IconBase'")
        const original = readFileSync(join(sourceDir, 'react/icons', file.target.split('/').at(-1)!), 'utf8')
        const expected = original.split('\n').filter((line) => !line.startsWith('//')).join('\n')
          .replace("from '../IconBase'", "from './IconBase'")
        expect(file.content).toBe(expected)
        expect(file.content).toMatch(/export const \w+Icon = \w+\n$/)
      }
    }
  })

  it('never includes Solid path data in a Line item or the free full set', () => {
    generateIconRegistry({ sourceDir, outDir })
    for (const name of NAMES) {
      const line = readItem(`icon-${name}`).files[0].content
      const solid = readItem(`icon-${name}-solid`).files[0].content
      expect(line).toContain(STYLES[0].path)
      expect(solid).toContain(STYLES[2].path)
      expect(line).not.toContain(STYLES[2].path)
    }
    const bundle = readItem('icons').files.map((file) => file.content).join('\n')
    for (const style of STYLES.slice(1)) expect(bundle).not.toContain(style.path)
  })

  it('preserves CRLF line endings and ordinary comments', () => {
    const filename = join(sourceDir, 'react/icons/search.tsx')
    const source = readFileSync(filename, 'utf8') + '// Keep this comment.\n'
    writeFileSync(filename, source.replaceAll('\n', '\r\n'))
    generateIconRegistry({ sourceDir, outDir })
    const content = readItem('icon-search').files[0].content
    expect(content).toContain('// Keep this comment.\r\n')
    expect(content).not.toMatch(/(?<!\r)\n/)
  })

  it('writes a geometry-free catalog with each icon\'s category, tags and style tiers', () => {
    const metaFile = join(workDir, 'icons.generated.json')
    writeFileSync(metaFile, JSON.stringify([{ name: 'search', category: 'interface', tags: ['find', 'magnifier'], added: null, isNew: false }]))
    generateIconRegistry({ sourceDir, outDir, metaFile })
    const raw = readFileSync(join(outDir, 'icons-index.json'), 'utf8')
    for (const { path } of STYLES) expect(raw).not.toContain(path)
    const catalog = JSON.parse(raw)
    expect(catalog).toMatchObject({ name: 'icons-index', count: 3 })
    expect(catalog.styles.map((s: { style: string; tier: string }) => `${s.style}:${s.tier}`))
      .toEqual(['line:free', 'duotone:premium', 'solid:premium', 'solid-duotone:premium'])
    expect(catalog.icons).toEqual([
      { name: 'image-sparkle', category: null, tags: [] },
      { name: 'map', category: null, tags: [] },
      { name: 'search', category: 'interface', tags: ['find', 'magnifier'] },
    ])
  })

  it('writes nothing and logs once when no checkout exists', () => {
    expect(generateIconRegistry({ sourceDir: join(workDir, 'absent'), outDir }))
      .toEqual({ iconCount: 0, itemCount: 0 })
    expect(existsSync(outDir)).toBe(false)
    expect(console.log).toHaveBeenCalledExactlyOnceWith('icon-registry: no icon checkout; nothing written')
  })

  it('fails before writing when a style file is missing', () => {
    rmSync(join(sourceDir, 'react/icons/search-solid.tsx'))
    expect(() => generateIconRegistry({ sourceDir, outDir })).toThrow()
    expect(existsSync(outDir)).toBe(false)
  })
})
