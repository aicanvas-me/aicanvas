#!/usr/bin/env node
// Run after generate-registry.mjs, whose stale-file sweep removes icon items.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ICON_RUNTIME_NOTICE, LINE_ICON_NOTICE } from './lib/icon-notice.mjs'
import { iconSourceCandidates } from './lib/icon-source.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const REGISTRY_BASE = (process.env.AICANVAS_REGISTRY_BASE ?? 'https://aicanvas.me').replace(/\/+$/, '')
const MARKER = ['AICANVAS', 'PREMIUM', 'DO', 'NOT', 'COMMIT'].join('-')
const STYLES = [
  { suffix: '', label: 'Line' },
  { suffix: '-duotone', label: 'Duotone' },
  { suffix: '-solid', label: 'Solid' },
  { suffix: '-solid-duotone', label: 'Solid Duotone' },
]

function findIconSource() {
  return iconSourceCandidates(process.cwd()).find((dir) => existsSync(join(dir, 'react/IconBase.tsx')))
}

function shippedContent(source, notice) {
  // Keep the original line endings and all bytes outside these three comments
  // and the relative import, including the alias export and pure annotations.
  // A Line file and the runtime open with their licence notice.
  const head = notice ? `// ${notice}${source.includes('\r\n') ? '\r\n' : '\n'}` : ''
  return head + source.split(/(?<=\n)/)
    .filter((line) => !line.includes(MARKER)
      && !line.startsWith('// Generated by icons/tools/react.mjs')
      && !line.startsWith('// Alias for names that clash'))
    .join('')
    .replace(/\bfrom (['"])\.\.\/IconBase\1/g, 'from $1./IconBase$1')
}

function registryFile(sourceDir, sourcePath, filename, notice = null) {
  const target = `components/icons/${filename}`
  return {
    path: target,
    content: shippedContent(readFileSync(join(sourceDir, 'react', sourcePath), 'utf8'), notice),
    type: 'registry:ui',
    target,
  }
}

function registryItem(name, title, description, files, registryDependencies = []) {
  return {
    $schema: 'https://ui.shadcn.com/schema/registry-item.json',
    name,
    type: 'registry:ui',
    title,
    description,
    author: 'aicanvas <https://aicanvas.me>',
    ...(registryDependencies.length ? { registryDependencies } : {}),
    files,
  }
}

export function generateIconRegistry({
  sourceDir = findIconSource(),
  outDir = join(ROOT, 'registry-data'),
  baseUrl = REGISTRY_BASE,
  metaFile = join(ROOT, 'app/icons/_data/icons.generated.json'),
} = {}) {
  if (!sourceDir || !existsSync(join(sourceDir, 'react/IconBase.tsx'))) {
    console.log('icon-registry: no icon checkout; nothing written')
    return { iconCount: 0, itemCount: 0 }
  }

  const names = readdirSync(join(sourceDir, 'react/icons'))
    .filter((file) => /^[a-z0-9-]+\.tsx$/.test(file) && !/-(?:duotone|solid)\.tsx$/.test(file))
    .map((file) => file.slice(0, -4))
    .sort()
  const base = registryFile(sourceDir, 'IconBase.tsx', 'IconBase.tsx', ICON_RUNTIME_NOTICE)
  const items = [registryItem('icon-base', 'Icon base', 'Shared React runtime for AI Canvas icons.', [base])]
  const lineFiles = [base]
  const baseDependency = `${baseUrl.replace(/\/+$/, '')}/r/icon-base.json`

  for (const name of names) {
    const title = name.split('-').map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(' ')
    for (const { suffix, label } of STYLES) {
      const filename = `${name}${suffix}.tsx`
      const file = registryFile(sourceDir, `icons/${filename}`, filename, suffix ? null : LINE_ICON_NOTICE)
      items.push(registryItem(
        `icon-${name}${suffix}`,
        `${title} icon (${label})`,
        `${title} React icon in the ${label} style.`,
        [file],
        [baseDependency],
      ))
      if (!suffix) lineFiles.push(file)
    }
  }
  items.push(registryItem('icons', 'Icons (Line)', `All ${names.length} Line icons and their shared React runtime.`, lineFiles))

  // The catalog the MCP and agents search: names, categories, tags, never geometry.
  const meta = existsSync(metaFile) ? JSON.parse(readFileSync(metaFile, 'utf8')) : []
  const metaByName = new Map(meta.map((icon) => [icon.name, icon]))
  const catalog = {
    name: 'icons-index',
    description: 'Every AI Canvas icon: name, category and tags. Install one with icon-<name>[-style].json.',
    count: names.length,
    styles: STYLES.map(({ suffix, label }) => ({ style: suffix.slice(1) || 'line', label, suffix, tier: suffix ? 'premium' : 'free' })),
    icons: names.map((name) => ({ name, category: metaByName.get(name)?.category ?? null, tags: metaByName.get(name)?.tags ?? [] })),
  }

  // Read the complete set before writing, so an incomplete checkout fails
  // without leaving a partially generated set. The index and manifest belong
  // to the existing registry generator and are never read or written here.
  mkdirSync(outDir, { recursive: true })
  for (const item of items) {
    writeFileSync(join(outDir, `${item.name}.json`), JSON.stringify(item, null, 2) + '\n')
  }
  writeFileSync(join(outDir, 'icons-index.json'), JSON.stringify(catalog) + '\n')
  console.log(`icon-registry: ${names.length} icons × ${STYLES.length} styles + base + Line set = ${items.length} items, + icons-index`)
  return { iconCount: names.length, itemCount: items.length }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateIconRegistry()
}
